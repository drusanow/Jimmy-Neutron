#!/usr/bin/env python3
"""Generate neutr_src/wavetables.c for the wavetable lfo oscillator mode.

Every wave is defined by its harmonic amplitudes (all partials in sine phase, so
neighbour waves morph smoothly). Each wave is stored in WT_LEVELS band-limited
versions ("mip levels"). Level k is used for fundamentals up to 156.25 * 2^k Hz and
keeps only harmonics below 20 kHz there, so the 48 kHz output does not alias.
Table length per level is a power of two (TABLE_LENS). Longer tables keep linear
interpolation images (which fold back as aliasing) lower, at the cost of flash.

usage: gen_wavetables.py [output.c]
(WT_LENS and WT_NYQ environment variables override table lengths and harmonic limit,
 then set WT_WAVE_SIZE in wavetables.h to the value printed in the output file)
"""
import math
import os
import sys

# measured with tests/analyse_wavetable.py: worst aliasing about -49 dB, 41 kB of flash
TABLE_LENS = [int(x) for x in os.environ.get('WT_LENS', '512,512,512,256,256,256,256').split(',')]
LEVELS = len(TABLE_LENS)
BASE_F0 = 156.25          # top fundamental of level 0, Hz
NYQ_LIMIT = float(os.environ.get('WT_NYQ', 20000))       # highest harmonic frequency allowed, Hz
MAX_H = 127
TAPER_START = 0.75        # fraction of the level's harmonic limit where a cosine taper starts


def gauss(h, centre, width):
    return math.exp(-0.5 * ((h - centre) / width) ** 2)


# (name, amplitude of harmonic h)
WAVES = [
    ('sine', lambda h: 1.0 if h == 1 else 0.0),
    ('organ', lambda h: {1: 0.8, 2: 1.0, 3: 0.6, 4: 0.5, 6: 0.4, 8: 0.35, 10: 0.2, 12: 0.15, 16: 0.1}.get(h, 0.0)),
    ('vowel ah', lambda h: (gauss(h, 7, 2.0) + 0.7 * gauss(h, 12, 2.5) + 0.3 * gauss(h, 26, 4.0)) / math.sqrt(h) + 0.3 / h),
    ('vowel ee', lambda h: (gauss(h, 2.5, 1.2) + 0.6 * gauss(h, 20, 3.0) + 0.4 * gauss(h, 27, 3.0)) / math.sqrt(h) + 0.15 / h),
    ('hollow', lambda h: 1.0 / h ** 1.3 if h % 2 else 0.0),
    ('comb saw', lambda h: 0.0 if h % 3 == 0 else 1.0 / h),
    ('bell', lambda h: {1: 1.0, 3: 0.25, 5: 0.6, 7: 0.4, 11: 0.5, 13: 0.35, 17: 0.3, 23: 0.2, 31: 0.15}.get(h, 0.0)),
    ('resonant', lambda h: 1.0 / h + 1.5 * gauss(h, 16, 1.5) + 0.8 * gauss(h, 32, 2.0)),
]


def level_limit(level):
    return min(MAX_H, int(NYQ_LIMIT / (BASE_F0 * 2 ** level)))


def table_len(level):
    return TABLE_LENS[level]


def render(amp, level):
    n = table_len(level)
    hmax = level_limit(level)
    taper_from = TAPER_START * hmax
    partials = []
    for h in range(1, hmax + 1):
        a = amp(h)
        if a == 0.0:
            continue
        if h > taper_from and hmax > 2:
            a *= 0.5 * (1 + math.cos(math.pi * (h - taper_from) / (hmax + 1 - taper_from)))
        partials.append((h, a))
    return [sum(a * math.sin(2 * math.pi * h * i / n) for h, a in partials)
            for i in range(n)]


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else 'neutr_src/wavetables.c'
    lines = [
        '/* generated by tools/gen_wavetables.py - do not edit, change the script instead */',
        '#include "wavetables.h"',
        '',
        '//start of every level inside a wave',
        'const uint16_t wavetable_level_offset[WT_LEVELS] = {%s};' % ', '.join(
            str(sum(table_len(j) + 1 for j in range(k))) for k in range(LEVELS)),
        '//table length of every level, as log2',
        'const uint8_t wavetable_level_bits[WT_LEVELS] = {%s};' % ', '.join(
            str(table_len(k).bit_length() - 1) for k in range(LEVELS)),
        '',
        'const int16_t wavetable[WT_WAVES][WT_WAVE_SIZE] =',
        '{',
    ]
    for name, amp in WAVES:
        levels = [render(amp, k) for k in range(LEVELS)]
        peak = max(max(abs(v) for v in lv) for lv in levels)
        gain = 32000.0 / peak
        lines.append('\t{ // %s' % name)
        for k, lv in enumerate(levels):
            vals = [int(round(v * gain)) for v in lv]
            vals.append(vals[0])  # guard point for interpolation
            lines.append('\t\t// level %d, %d samples, harmonics <= %d' % (k, table_len(k), level_limit(k)))
            for i in range(0, len(vals), 16):
                lines.append('\t\t' + ', '.join('%6d' % v for v in vals[i:i + 16]) + ',')
        lines.append('\t},')
    lines.append('};')
    lines.append('')
    size = sum(table_len(k) + 1 for k in range(LEVELS))
    lines.insert(1, '// WT_WAVE_SIZE in wavetables.h must be %d' % size)
    lines.insert(3, '_Static_assert(WT_WAVE_SIZE == %d, "set WT_WAVE_SIZE in wavetables.h to %d");' % (size, size))
    with open(out, 'w') as f:
        f.write('\n'.join(lines))


if __name__ == '__main__':
    main()
